let current = 'en';

export function setLang(lang) {
  current = STRINGS[lang] ? lang : 'en';
  document.documentElement.lang = current;
  return current;
}

export function getLang() {
  return current;
}

/** t('key') or t('key', arg1, arg2) for function strings. */
export function t(key, ...args) {
  const v = STRINGS[current][key] ?? STRINGS.en[key] ?? key;
  return typeof v === 'function' ? v(...args) : v;
}

/** Pick name_en / name_th from any data object. */
export function nameOf(obj) {
  return current === 'th' ? obj.name_th || obj.name_en : obj.name_en;
}

/** The other language's name, shown smaller under the main one. */
export function altNameOf(obj) {
  return current === 'th' ? obj.name_en : obj.name_th;
}

/** Short line name for pills ("BTS Sukhumvit"). */
export function labelOf(line) {
  return current === 'th' ? line.label_th || line.name_th : line.label_en || line.name_en;
}
